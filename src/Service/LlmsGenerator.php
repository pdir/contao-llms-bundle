<?php

namespace Pdir\ContaoLlmsBundle\Service;

use Contao\CoreBundle\InsertTag\InsertTagParser;
use Contao\CoreBundle\Util\LocaleUtil;
use Contao\PageModel;
use Doctrine\DBAL\Connection;
use League\HTMLToMarkdown\Converter\TableConverter;
use League\HTMLToMarkdown\HtmlConverter;
use Psr\Log\LoggerInterface;
use Symfony\Contracts\HttpClient\Exception\ExceptionInterface as HttpClientExceptionInterface;
use Symfony\Contracts\HttpClient\HttpClientInterface;
use Symfony\Component\DomCrawler\Crawler;
use Symfony\Contracts\Translation\TranslatorInterface;

class LlmsGenerator
{
    /**
     * Markup between these comments is not added to the LLMs files, e.g. content
     * elements with the option "Exclude from LLMs files" (see
     * LlmsExcludeListener). They can also be used in templates.
     */
    public const EXCLUDE_START = '<!-- llms::stop -->';

    public const EXCLUDE_END = '<!-- llms::continue -->';

    /**
     * Generated page contents are refreshed at least once within this period
     * (in seconds), even if the page itself has not changed.
     */
    private const MAX_AGE = 86400;

    /**
     * Pages in this section can be skipped by LLMs (see llmstxt.org).
     */
    private const OPTIONAL_SECTION = 'Optional';

    /**
     * Item types whose content is stored in tl_llms_content, with their table.
     */
    private const STORED_TYPES = [
        'news' => 'tl_news',
        'event' => 'tl_calendar_events',
    ];

    private int $maxAge = self::MAX_AGE;

    private int $failures = 0;

    public function __construct(
        private HttpClientInterface $client,
        private Connection $connection,
        private InsertTagParser $insertTagParser,
        private TranslatorInterface $translator,
        private ?LoggerInterface $logger = null,
    )
    {
    }

    /**
     * Sets the age (in seconds) from which stored contents are refreshed.
     */
    public function setMaxAge(int $maxAge): void
    {
        $this->maxAge = $maxAge;
    }

    /**
     * Returns the number of contents that could not be fetched, so their
     * stored content was used instead.
     */
    public function getFailures(): int
    {
        return $this->failures;
    }

    /**
     * @param string $filePath The path of the files relative to the start page, e.g. "de/" for /de/llms.txt
     */
    public function generateBasic(PageModel $rootPage, array $sections, string $startPage, string $filePath = ''): string
    {
        $locale = LocaleUtil::formatAsLocale((string) $rootPage->language);
        $lines = $this->getHeader($rootPage, (string) $rootPage->llmsTxt, $sections);
        $groups = [];
        $optional = [];

        foreach ($sections as $section) {
            // Distinguish the sections of multiple languages
            $suffix = \count($sections) > 1 ? sprintf(' (%s)', $section['root']->language) : '';
            $defaultName = $this->trans('keyPages', [], LocaleUtil::formatAsLocale((string) $section['root']->language));

            foreach ($section['items'] as $item) {
                if ($this->isKnownEmptyPage($item)) {
                    continue;
                }

                $link = $this->formatLink($item['title'], $item['url'], $item['description']);
                $name = trim((string) ($item['section'] ?? ''));

                if (0 === strcasecmp($name, self::OPTIONAL_SECTION)) {
                    $optional[] = $link;
                } else {
                    $groups[('' !== $name ? $name : $defaultName).$suffix][] = $link;
                }
            }
        }

        foreach ($groups as $name => $links) {
            $lines[] = '';
            $lines[] = '## '.$name;
            $lines[] = '';
            array_push($lines, ...$links);
        }

        $lines = $this->getLegalSection($lines, $sections, $locale, '##');
        $lines = $this->getFooter($lines, $rootPage, $startPage, $locale, '##');

        // The llms-full.txt is not needed for a quick overview ($startPage ends with a slash)
        if ($rootPage->llmsFull) {
            $optional[] = $this->formatLink('llms-full.txt', $startPage.$filePath.'llms-full.txt', $this->trans('fullTxt', [], $locale));
        }

        // The sitemap is generated by Contao for every domain
        if ($rootPage->llmsSitemap) {
            $optional[] = $this->formatLink('Sitemap', $startPage.'sitemap.xml', $this->trans('sitemap', [], $locale));
        }

        // The "Optional" section can be skipped by LLMs and therefore comes last (see llmstxt.org)
        if ($optional) {
            $lines[] = '';
            $lines[] = '## '.self::OPTIONAL_SECTION;
            $lines[] = '';
            array_push($lines, ...$optional);
        }

        return implode("\n", $lines);
    }

    public function generateFull(PageModel $rootPage, array $sections, string $startPage): string
    {
        $locale = LocaleUtil::formatAsLocale((string) $rootPage->language);
        $lines = $this->getHeader($rootPage, (string) $rootPage->llmsFullTxt, $sections);
        $lines[] = '';
        $lines[] = $this->getStatusLine($rootPage, $sections, $locale);
        $lines[] = '';
        $lines[] = '---';

        foreach ($sections as $section) {
            foreach ($section['items'] as $item) {
                // Also tidies content stored by older versions and manual descriptions
                $fullDescription = $this->removeBlankLines($this->getFullDescription($item, $startPage));

                // Skip pages, news and events without content of their own (e.g. redirects or empty reader pages)
                if (('page' === $item['type'] || isset(self::STORED_TYPES[$item['type']])) && '' === $fullDescription) {
                    continue;
                }

                // Every page is a top-level section, its content only uses one more level
                $lines[] = '';
                $lines[] = sprintf('# %s', $item['title']);
                $lines[] = '';
                $lines[] = sprintf('URL: %s', $item['url']);

                if ('' !== ($publication = $this->getPublicationLine($item, $locale))) {
                    $lines[] = $publication;
                }

                $lines[] = sprintf('%s: %s', $this->trans('lastModified', [], $locale), date('Y-m-d\TH:i:sP', max($item['tstamp'], $item['lastModified'])));

                if ('' !== trim((string) $item['description'])) {
                    $lines[] = '';
                    array_push($lines, ...$this->formatQuote($item['description']));
                }

                // Images of the content are removed, only the selected ones are added
                foreach ($item['images'] ?? [] as $image) {
                    $lines[] = '';
                    $lines[] = $this->formatImage($image, $startPage);
                }

                // Add the full description if available
                if ('' !== $fullDescription) {
                    $lines[] = '';
                    $lines[] = $this->flattenHeadings($fullDescription, (string) $item['title']);
                }

                $lines[] = '';
                $lines[] = '---';
            }
        }

        $lines = $this->getLegalSection($lines, $sections, $locale, '#');
        $lines = $this->getFooter($lines, $rootPage, $startPage, $locale, '#');

        return implode("\n", $lines);
    }

    /**
     * @param array{path?: string, url?: string, alt?: string} $image A path relative to the website root or an absolute URL
     */
    private function formatImage(array $image, string $baseUrl): string
    {
        $url = (string) ($image['url'] ?? '');

        if ('' === $url) {
            $url = $baseUrl.implode('/', array_map('rawurlencode', explode('/', ltrim((string) ($image['path'] ?? ''), '/'))));
        }

        return sprintf('![%s](%s)', $this->escapeLinkText((string) ($image['alt'] ?? '')), $this->escapeUrl($url));
    }

    /**
     * Returns e.g. "Datum: 25.10.2026 · Autor: Max Mustermann" for items with
     * a publication date (news), formatted according to the language.
     */
    private function getPublicationLine(array $item, string $locale): string
    {
        $parts = [];

        if (($item['date'] ?? 0) > 0) {
            $date = (new \IntlDateFormatter($locale, \IntlDateFormatter::MEDIUM, \IntlDateFormatter::NONE))->format((int) $item['date']);
            $parts[] = $this->trans('date', [], $locale).': '.$date;
        }

        if ('' !== ($author = trim((string) ($item['author'] ?? '')))) {
            $parts[] = $this->trans('author', [], $locale).': '.$author;
        }

        return implode(' · ', $parts);
    }

    /**
     * Limits the headings of a page content to one level below the page
     * heading: h1 and h2 become "##", deeper headings bold text (e.g. the
     * questions of an FAQ). A first heading that repeats the page title is
     * removed, as is a single full stop at the end of a heading.
     *
     * Applied on output, so it also covers stored and manual contents.
     */
    private function flattenHeadings(string $markdown, string $title): string
    {
        $lines = explode("\n", $markdown);
        $inCode = false;
        $isFirst = true;

        foreach ($lines as $i => $line) {
            if (str_starts_with(ltrim($line), '```')) {
                $inCode = !$inCode;

                continue;
            }

            if ($inCode || !preg_match('/^(#{1,6})[ \t]+(.*?)(?:[ \t]+#+)?[ \t]*$/', $line, $matches)) {
                continue;
            }

            $text = preg_replace('/(?<![.\s])\.$/u', '', trim($matches[2]));

            if ('' === $text || ($isFirst && 0 === strcasecmp($text, trim($title)))) {
                $lines[$i] = '';
            } elseif (\strlen($matches[1]) <= 2) {
                $lines[$i] = '## '.$text;
            } else {
                // Bold text within the heading would end the bold text early
                $lines[$i] = '**'.str_replace('**', '', $text).'**';
            }

            $isFirst = false;
        }

        return $this->removeBlankLines(implode("\n", $lines));
    }

    private function getHeader(PageModel $rootPage, string $instructions, array $sections): array
    {
        $lines = [];
        $lines[] = '# ' . ($rootPage->llmsTitle ?: ($rootPage->pageTitle ?: $rootPage->title));

        // Fall back to the description of the first page (usually the start page)
        $description = (string) ($rootPage->llmsDescription ?: $rootPage->description);

        if ('' === $description) {
            $description = (string) ($sections[0]['items'][0]['description'] ?? '');
        }

        // Only the first paragraph is the summary (blockquote), further paragraphs
        // are details in regular Markdown (see llmstxt.org)
        $description = trim(preg_replace('/\R/u', "\n", $description));
        [$summary, $details] = preg_split('/\n[ \t]*\n/', $description, 2) + [1 => ''];

        if ('' !== $summary) {
            $lines[] = '';
            array_push($lines, ...$this->formatQuote($summary));
        }

        // Keep the indentation, e.g. of nested lists
        if ('' !== ($details = trim(preg_replace(['/[ \t]+$/m', '/\n{3,}/'], ['', "\n\n"], $details), "\n"))) {
            $lines[] = '';
            $lines[] = $details;
        }

        if ('' !== ($instructions = trim($instructions))) {
            $lines[] = '';
            $lines[] = $instructions;
        }

        return $lines;
    }

    /**
     * Returns e.g. "Stand: Oktober 2026 · Sprache: Deutsch · Support: info@example.org"
     * with the month of the latest change, the languages of the root pages and
     * the LLMs e-mail address (if any).
     */
    private function getStatusLine(PageModel $rootPage, array $sections, string $locale): string
    {
        $lastModified = 0;
        $languages = [];

        foreach ($sections as $section) {
            $language = \Locale::getDisplayLanguage((string) $section['root']->language, $locale);
            $languages[] = mb_strtoupper(mb_substr($language, 0, 1)).mb_substr($language, 1);

            foreach ($section['items'] as $item) {
                $lastModified = max($lastModified, (int) ($item['tstamp'] ?? 0), (int) ($item['lastModified'] ?? 0));
            }
        }

        // Stand-alone month name, which differs from the one in a full date in some languages (e.g. Polish)
        $date = (new \IntlDateFormatter($locale, \IntlDateFormatter::NONE, \IntlDateFormatter::NONE, null, null, 'LLLL yyyy'))->format($lastModified ?: time());

        $parts = [
            $this->trans('status', [], $locale).': '.$date,
            $this->trans('language', [], $locale).': '.implode(', ', array_unique(array_filter($languages))),
        ];

        if ('' !== ($email = (string) $rootPage->llmsEmail)) {
            $parts[] = $this->trans('support', [], $locale).': '.$email;
        }

        return implode(' · ', $parts);
    }

    /**
     * Returns the Markdown body of an item. Page bodies are generated from the
     * rendered page and stored, so the page is only fetched again if it has
     * changed since the last run or the stored content is older than MAX_AGE.
     * Manually overridden descriptions are never replaced.
     */
    private function getFullDescription(array $item, string $baseUrl): string
    {
        $model = $item['model'] ?? null;

        if ('article' === $item['type'] && null !== $model) {
            // Contao paths like "files/…" are relative to the website root, like the <base> tag of a page
            return $this->htmlToMarkdown('<html><head><base href="'.htmlspecialchars($baseUrl).'"></head><body>'.$this->insertTagParser->replaceInline((string) $model->teaser).'</body></html>', $item['url']);
        }

        if (isset(self::STORED_TYPES[$item['type']]) && null !== $model) {
            return $this->getStoredContent(self::STORED_TYPES[$item['type']], (int) $model->id, $item['url'], (int) $model->tstamp);
        }

        if ('page' !== $item['type'] || !$model instanceof PageModel) {
            return '';
        }

        $page = $model;
        $stored = trim((string) $page->llmsFullDescription);

        if ($page->llmsFullDescriptionOverride) {
            return $stored;
        }

        $generatedAt = (int) $page->llmsFullDescriptionGenerated;
        $changed = max((int) $page->tstamp, (int) $page->llmsLastModified);

        // An empty stored content is valid as well (page without content of its own)
        if ($generatedAt > 0 && $generatedAt >= $changed && $generatedAt > time() - $this->maxAge) {
            return $stored;
        }

        try {
            $generated = $this->generateFromUrl($item['url']);
        } catch (HttpClientExceptionInterface|\RuntimeException $exception) {
            ++$this->failures;
            $this->logger?->warning(sprintf('Could not generate LLMs description for page ID %s: %s', $page->id, $exception->getMessage()));

            return $stored;
        }

        $this->connection->update(
            'tl_page',
            ['llmsFullDescription' => $generated, 'llmsFullDescriptionGenerated' => time()],
            ['id' => (int) $page->id],
        );

        return $generated;
    }

    /**
     * Returns the Markdown of a record that has no fields of its own to store
     * it (news and events). It is stored in tl_llms_content and refreshed under the
     * same conditions as the content of pages.
     */
    private function getStoredContent(string $source, int $sourceId, string $url, int $changed): string
    {
        $row = $this->connection->fetchAssociative('SELECT tstamp, url, content FROM tl_llms_content WHERE source = ? AND sourceId = ?', [$source, $sourceId]);
        $stored = false !== $row ? trim((string) $row['content']) : '';

        if (false !== $row && $row['url'] === $url && (int) $row['tstamp'] >= $changed && (int) $row['tstamp'] > time() - $this->maxAge) {
            return $stored;
        }

        try {
            $generated = $this->generateFromUrl($url);
        } catch (HttpClientExceptionInterface|\RuntimeException $exception) {
            ++$this->failures;
            $this->logger?->warning(sprintf('Could not generate LLMs content for %s ID %s: %s', $source, $sourceId, $exception->getMessage()));

            return $stored;
        }

        $this->connection->transactional(function (Connection $connection) use ($source, $sourceId, $url, $generated): void {
            $connection->delete('tl_llms_content', ['source' => $source, 'sourceId' => $sourceId]);
            $connection->insert('tl_llms_content', ['tstamp' => time(), 'source' => $source, 'sourceId' => $sourceId, 'url' => $url, 'content' => $generated]);
        });

        return $generated;
    }

    /**
     * @param string $heading The heading marker: "##" in the llms.txt, "#" in the llms-full.txt (where pages are top-level sections)
     */
    private function getFooter(array $lines, PageModel $rootPage, string $startPage, string $locale, string $heading): array
    {
        $email = (string) $rootPage->llmsEmail;
        $phone = (string) $rootPage->llmsPhone;

        if ('' !== $email || '' !== $phone) {
            $lines[] = '';
            $lines[] = $heading.' '.$this->trans('contact', [], $locale);
            $lines[] = '';

            if ('' !== $email) {
                $lines[] = '- '.$this->trans('email', [], $locale).': '.$email;
            }

            if ('' !== $phone) {
                $lines[] = '- '.$this->trans('phone', [], $locale).': '.$phone;
            }
        }

        if (!$rootPage->llmsGuidelines) {
            return $lines;
        }

        $lines[] = '';
        $lines[] = $heading.' '.$this->trans('guidelines', [], $locale);
        $lines[] = '';
        $lines[] = '- '.$this->trans('guidelineAttribute', [$rootPage->title], $locale);
        $lines[] = '- '.$this->trans('guidelineLink', [], $locale);

        if ('' !== $email) {
            $lines[] = '- '.$this->trans('guidelineCommercial', [$email], $locale);
        }

        $lines[] = '- '.$this->trans('guidelineEducation', [], $locale);

        $lines[] = '';
        $lines[] = $heading.' '.$this->trans('attribution', [], $locale);
        $lines[] = '';
        $lines[] = $this->trans('attributionText', [], $locale);
        $lines[] = $this->trans('attributionExample', [$rootPage->title, $startPage], $locale);

        return $lines;
    }

    /**
     * Adds the legal pages selected in the root pages (imprint, privacy
     * policy, …) as links. The section is omitted if no pages are selected.
     */
    private function getLegalSection(array $lines, array $sections, string $locale, string $heading): array
    {
        $links = [];

        foreach ($sections as $section) {
            foreach ($section['legal'] ?? [] as $item) {
                $title = $item['title'];

                // Distinguish the pages of multiple languages
                if (\count($sections) > 1) {
                    $title .= sprintf(' (%s)', $section['root']->language);
                }

                $links[] = $this->formatLink($title, $item['url'], $item['description']);
            }
        }

        if ($links) {
            $lines[] = '';
            $lines[] = $heading.' '.$this->trans('legal', [], $locale);
            $lines[] = '';
            array_push($lines, ...$links);
        }

        return $lines;
    }

    private function formatLink(string $title, string $url, string $description = ''): string
    {
        $link = sprintf('- [%s](%s)', $this->escapeLinkText($title), $this->escapeUrl($url));

        // Further lines of the description are indented, so they stay part of the list item
        $description = implode("\n  ", array_filter($this->splitLines($description), static fn (string $line): bool => '' !== $line));

        return '' !== $description ? $link.': '.$description : $link;
    }

    /**
     * Formats a text as a blockquote and keeps its line breaks; empty lines
     * separate paragraphs within the quote.
     *
     * @return list<string>
     */
    private function formatQuote(string $text): array
    {
        return array_map(static fn (string $line): string => '' !== $line ? '> '.$line : '>', $this->splitLines($text));
    }

    /**
     * Splits a text into trimmed lines with single spaces; multiple empty
     * lines are reduced to one.
     *
     * @return list<string>
     */
    private function splitLines(string $text): array
    {
        $text = preg_replace("/\n{3,}/", "\n\n", preg_replace('/[ \t]*\R[ \t]*/u', "\n", trim($text)));

        return '' === $text ? [] : array_map(static fn (string $line): string => preg_replace('/[^\S\n]+/u', ' ', $line), explode("\n", $text));
    }

    private function trans(string $key, array $parameters, string $locale): string
    {
        return $this->translator->trans('llms.'.$key, $parameters, 'contao_llms', $locale);
    }

    /**
     * Returns an empty string if the URL has no content of its own (redirect,
     * not found, access denied).
     */
    public function generateFromUrl(string $url): string
    {
        $html = $this->fetchHtml($url);

        return null === $html ? '' : $this->htmlToMarkdown($html, $url);
    }

    /**
     * Converts the main content area of an HTML document to Markdown. Relative
     * link URLs are resolved against $url (or the <base> tag).
     */
    private function htmlToMarkdown(string $html, string $url): string
    {
        $crawler = new Crawler($this->removeExcludedMarkup($html), $url);

        // Only convert the main content area, not the whole layout
        foreach (['#main', 'main', 'body'] as $selector) {
            $node = $crawler->filter($selector);

            if ($node->count() > 0) {
                $this->removeNoise($node);
                $this->prepareHeadings($node);
                $this->prepareTables($node);

                $node->filter('a[href]')->each(static fn (Crawler $link) => $link->getNode(0)->setAttribute('href', $link->link()->getUri()));

                return $this->toMarkdown($node->html());
            }
        }

        return '';
    }

    /**
     * Removes the markup between EXCLUDE_START and EXCLUDE_END. Nested pairs
     * (e.g. an excluded element inside an excluded element group) are removed
     * from the inside out. A start comment without an end is ignored.
     */
    private function removeExcludedMarkup(string $html): string
    {
        $pattern = '/'.preg_quote(self::EXCLUDE_START, '/').'(?:(?!'.preg_quote(self::EXCLUDE_START, '/').').)*?'.preg_quote(self::EXCLUDE_END, '/').'/s';

        do {
            $html = preg_replace($pattern, '', $html, -1, $count) ?? $html;
        } while ($count > 0);

        return $html;
    }

    private function toMarkdown(string $html): string
    {
        $converter = new HtmlConverter([
            'header_style' => 'atx',
            'strip_tags' => true,
            'remove_nodes' => 'script style noscript template nav header footer aside form iframe svg',
        ]);

        // Tables are not converted by default, only their cell contents would remain
        $converter->getEnvironment()->addConverter(new TableConverter());

        // The converter encodes &, <, > and backticks as HTML entities again
        $markdown = html_entity_decode($converter->convert($html), ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $markdown = $this->normalizeWhitespace(str_replace("\u{00A0}", ' ', $markdown));

        return trim($this->removeBlankLines($markdown));
    }

    /**
     * Removes elements that only add noise to the Markdown: images (including
     * figures with their captions), title attributes and links without text
     * (e.g. around images). Images for the LLMs files are selected in the
     * page settings instead (see LlmsAdapterTrait::getImages()).
     */
    private function removeNoise(Crawler $node): void
    {
        foreach ($node->filter('figure') as $figure) {
            if ($figure->getElementsByTagName('img')->length > 0) {
                $figure->parentNode?->removeChild($figure);
            }
        }

        foreach ($node->filter('picture, img') as $image) {
            $image->parentNode?->removeChild($image);
        }

        foreach ($node->filter('[title]') as $element) {
            $element->removeAttribute('title');
        }

        foreach ($node->filter('a') as $link) {
            if ('' === trim(str_replace("\u{00A0}", ' ', $link->textContent))) {
                $link->parentNode?->removeChild($link);
            }
        }
    }

    /**
     * Separates the parts of headings that are only separated by CSS, e.g. a
     * kicker and the main headline in two block-level spans ("So funktioniert
     * es" and "In vier Schritten" become "So funktioniert es: In vier
     * Schritten"). Line breaks become spaces, as Markdown headings are single
     * lines.
     */
    private function prepareHeadings(Crawler $node): void
    {
        foreach ($node->filter('h1, h2, h3, h4, h5, h6') as $heading) {
            $document = $heading->ownerDocument;

            foreach (iterator_to_array($heading->getElementsByTagName('br')) as $break) {
                $break->parentNode->replaceChild($document->createTextNode(' '), $break);
            }

            $previous = null;

            foreach (iterator_to_array($heading->childNodes) as $child) {
                if (XML_ELEMENT_NODE !== $child->nodeType) {
                    $previous = null;

                    continue;
                }

                $text = trim(str_replace("\u{00A0}", ' ', $child->textContent));

                if (null !== $previous && '' !== $text) {
                    $separator = preg_match('/[.:!?;,–—-]$/u', $previous) ? ' ' : ': ';
                    $heading->insertBefore($document->createTextNode($separator), $child);
                }

                $previous = '' !== $text ? $text : $previous;
            }
        }
    }

    /**
     * Prepares tables for the conversion to Markdown tables: the footer is
     * moved behind the body (Contao renders it before) and tables without a
     * header get an empty one, because Markdown would otherwise turn the first
     * row into the header. Tables without content are removed.
     */
    private function prepareTables(Crawler $node): void
    {
        foreach ($node->filter('table') as $table) {
            if ('' === trim(str_replace("\u{00A0}", ' ', $table->textContent))) {
                $table->parentNode->removeChild($table);

                continue;
            }

            $sections = [];
            $columns = 0;

            foreach ($table->childNodes as $child) {
                $sections[strtolower($child->nodeName)][] = $child;
            }

            foreach ($sections['tfoot'] ?? [] as $footer) {
                $table->appendChild($footer);
            }

            if (isset($sections['thead'])) {
                continue;
            }

            foreach ($table->getElementsByTagName('tr') as $row) {
                $columns = max($columns, \count(array_filter(iterator_to_array($row->childNodes), static fn (\DOMNode $cell): bool => \in_array(strtolower($cell->nodeName), ['td', 'th'], true))));
            }

            if (0 === $columns) {
                continue;
            }

            $document = $table->ownerDocument;
            $header = $document->createElement('thead');
            $row = $header->appendChild($document->createElement('tr'));

            for ($i = 0; $i < $columns; ++$i) {
                $row->appendChild($document->createElement('th'));
            }

            // After the caption, before the body
            $table->insertBefore($header, $sections['tbody'][0] ?? $sections['tr'][0] ?? null);
        }
    }

    /**
     * Empties lines that only contain whitespace and reduces multiple empty
     * lines to one. Code blocks are left untouched.
     */
    private function removeBlankLines(string $markdown): string
    {
        $result = [];
        $inCode = false;

        foreach (explode("\n", preg_replace('/\R/u', "\n", $markdown)) as $line) {
            if (str_starts_with(ltrim($line), '```')) {
                $inCode = !$inCode;
            }

            if (!$inCode && preg_match('/^[\s\x{00A0}]*$/u', $line)) {
                if ('' !== end($result)) {
                    $result[] = '';
                }

                continue;
            }

            $result[] = $line;
        }

        return trim(implode("\n", $result), "\n");
    }

    /**
     * Removes whitespace-only lines and superfluous indentation, but keeps
     * list indentation, hard line breaks and code blocks.
     */
    private function normalizeWhitespace(string $markdown): string
    {
        $lines = explode("\n", $markdown);
        $inCode = false;

        foreach ($lines as $i => $line) {
            if (str_starts_with(ltrim($line), '```')) {
                $inCode = !$inCode;
                $lines[$i] = ltrim($line);

                continue;
            }

            if ($inCode) {
                continue;
            }

            if ('' === trim($line)) {
                $lines[$i] = '';

                continue;
            }

            $hardBreak = str_ends_with($line, '  ');
            $line = rtrim($line);

            // Keep the indentation of nested lists and quotes only
            if (!preg_match('/^\s+([-*+>]|\d+[.)])\s/', $line)) {
                $line = ltrim($line);
            }

            // Collapse spaces after the heading marker
            $line = preg_replace('/^(#{1,6})\s+/', '$1 ', $line);

            // Line breaks in table cells become multiple spaces, as Markdown tables cannot contain them
            if (str_starts_with($line, '|')) {
                $line = preg_replace('/ {2,}/', ' ', $line);
                $hardBreak = false;
            }

            $lines[$i] = $line.($hardBreak ? '  ' : '');
        }

        // A hard line break before an empty line or the end is pointless
        return preg_replace('/ {2}(?=\n\n|\n?$)/', '', implode("\n", $lines));
    }

    private function escapeLinkText(string $text): string
    {
        return addcslashes($text, '[]\\');
    }

    private function escapeUrl(string $url): string
    {
        return str_replace([' ', '(', ')'], ['%20', '%28', '%29'], $url);
    }

    /**
     * Returns null for redirects and client errors. Server errors (e.g. 503 in
     * maintenance mode) throw an exception, so the stored content is kept.
     */
    private function fetchHtml(string $url): ?string
    {
        // Do not follow redirects, otherwise the content of the target page
        // would be stored for this page
        $response = $this->client->request('GET', $url, ['timeout' => 10, 'max_redirects' => 0]);
        $status = $response->getStatusCode();

        if ($status >= 300 && $status < 500) {
            return null;
        }

        if (200 !== $status) {
            throw new \RuntimeException(sprintf('Failed to fetch URL %s (HTTP %s)', $url, $status));
        }

        return $response->getContent();
    }

    /**
     * Pages whose content has been generated as empty before (e.g. redirects
     * or empty reader pages) are left out of the llms.txt as well.
     */
    private function isKnownEmptyPage(array $item): bool
    {
        $page = $item['model'] ?? null;

        return 'page' === $item['type']
            && $page instanceof PageModel
            && !$page->llmsFullDescriptionOverride
            && (int) $page->llmsFullDescriptionGenerated > 0
            && '' === trim((string) $page->llmsFullDescription);
    }
